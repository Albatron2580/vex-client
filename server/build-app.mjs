// Bundles the phone app (app/) into src/phoneApp.gen.ts so the Worker can serve it. Run: node build-app.mjs
import fs from "node:fs";
const read = (f) => fs.readFileSync(new URL(`./app/${f}`, import.meta.url));
const files = {
  "/app": { type: "text/html; charset=utf-8", body: read("index.html").toString("utf8") },
  "/app/sw.js": { type: "text/javascript; charset=utf-8", body: read("sw.js").toString("utf8") },
  "/app/manifest.webmanifest": { type: "application/manifest+json", body: read("manifest.webmanifest").toString("utf8") },
  "/app/icon-192.png": { type: "image/png", b64: read("icon-192.png").toString("base64") },
  "/app/icon-512.png": { type: "image/png", b64: read("icon-512.png").toString("base64") },
};
fs.writeFileSync(new URL("./src/phoneApp.gen.ts", import.meta.url),
  "// Generated by build-app.mjs from app/ — don't edit by hand.\nexport const PHONE_APP: Record<string, { type: string; body?: string; b64?: string }> = " + JSON.stringify(files) + ";\n");
console.log("phone app bundled");
